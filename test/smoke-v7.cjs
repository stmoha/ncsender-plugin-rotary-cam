const { chromium } = require('playwright'); const { spawn } = require('child_process'); const path = require('path'), fs = require('fs');
(async () => {
  const PORT = 8795, out = process.argv[2] || 'test/out-v7/smoke'; fs.mkdirSync(out, { recursive: true });
  const srv = spawn('node', [path.join(__dirname, 'harness/serve.mjs'), String(PORT)], { stdio: ['ignore', 'pipe', 'inherit'] });
  await new Promise((r) => srv.stdout.once('data', r));
  const browser = await chromium.launch({ args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const page = await (await browser.newContext({ viewport: { width: 1500, height: 950 } })).newPage();
  const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
  await page.goto(`http://localhost:${PORT}/`);
  await page.click('#open'); await page.waitForFunction(() => window.RotaryCam && window.RotaryCam.__state && window.RotaryCam.__state.tools.length > 0, null, { timeout: 30000 });
  await page.setInputFiles('#rcam-root input[type=file]', 'test/chin_test.step');
  await page.waitForFunction(() => window.RotaryCam.__state.mesh, null, { timeout: 120000 });
  await page.selectOption('#rcam-root .rc-centre', 'origin'); await page.waitForTimeout(300);
  await page.fill('#rc-stock-dia-round', '44'); await page.dispatchEvent('#rc-stock-dia-round', 'change'); await page.waitForTimeout(1500);
  console.log(JSON.stringify(await page.evaluate(() => window.RotaryCam.__state.job.rig.tc)));
  await page.click('[data-view=whole]'); await page.waitForTimeout(500);
  await page.screenshot({ path: out + '/1-setup.png' });
  await page.evaluate(() => { const d = document.querySelector('#rcam-root details[data-sec=toolchange]'); d.open = true; d.scrollIntoView(); });
  await page.waitForTimeout(300);
  await page.screenshot({ path: out + '/2-toolchange-section.png' });
  for (const [s, id] of [['rough', '11'], ['finish', '13']]) { await page.evaluate((x) => { document.querySelector('#rcam-root details[data-sec=' + x + ']').open = true; }, s); await page.selectOption(`#rc-${s}-tool`, id); }
  await page.click('#rcam-root .rc-gen');
  await page.waitForFunction(() => window.RotaryCam.__state.program || (!window.RotaryCam.__state.busy && window.RotaryCam.__state.problems.length), null, { timeout: 600000, polling: 500 });
  console.log(await page.$eval('#rcam-root .rc-msgs', (el) => el.innerText));
  const g = await page.evaluate(() => window.RotaryCam.__state.program.gcode.split('\n').slice(0, 30).join('\n'));
  console.log(g);
  await page.click('[data-view=whole]'); await page.waitForTimeout(500);
  await page.screenshot({ path: out + '/3-generated.png' });
  await page.click('[data-tab=sim]');
  await page.waitForFunction(() => window.RotaryCam.sim && window.RotaryCam.sim.checked, null, { timeout: 600000, polling: 500 });
  console.log(JSON.stringify(await page.evaluate(() => window.RotaryCam.__state.simReport.holder)));
  await page.screenshot({ path: out + '/4-sim.png' });
  console.log('errors:', errs);
  await browser.close(); srv.kill();
})();
